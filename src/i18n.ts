const TABLES: Record<Lang, Record<StringKey, string>> = { en: EN, ru: RU };

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const text = TABLES[lang][key] ?? EN[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : text;
}

/** The translate function for the current language; re-renders when the language changes. */
export function useT(): Translate {
  const lang = useNavigator((s) => s.lang);
  return (key, vars) => translate(lang, key, vars);
}
